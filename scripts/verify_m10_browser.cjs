let activeBrowser;
const { chromium, request } = require("playwright");
const fs = require("node:fs");
const path = require("node:path");
(async()=>{
 const root=path.resolve(__dirname,".."),base="http://127.0.0.1:8050";
 const privateDir=path.join(root,"m10","private"),out=path.join(privateDir,"verification");
 fs.mkdirSync(out,{recursive:true});
 const token=fs.readFileSync(path.join(privateDir,"access-token.txt"),"utf8").trim();
 const checks=[],errors=[];
 const client=await request.newContext();
 for(const p of ["/api/v1/runs","/api/v1/audit","/api/v1/openapi.json","/api/v1/microscopy","/api/v1/runs/LAB005-2026-08/exports/result.json"]){
  const r=await client.get(base+p);if(r.status()!==401)throw Error("Anonymous access accepted: "+p);
  checks.push({check:"anonymous_denied",path:p,status:r.status()});
 }
 const browser=activeBrowser=await chromium.launch({channel:"msedge",headless:true});
 const context=await browser.newContext({viewport:{width:1500,height:1000}});
 const page=await context.newPage();page.on("pageerror",e=>errors.push(e.message));
 await page.goto(base,{waitUntil:"domcontentloaded"});
 await page.locator('input[name="key"]').fill(token);
 await page.getByRole("button",{name:"Open workspace"}).click();
 await page.locator("#run option[value=LAB005-2026-08]").waitFor({state:"attached"});
 await page.locator("#run").selectOption("LAB005-2026-08");
 await page.locator(".chart svg").first().waitFor();
 await page.locator("#message").filter({hasText:"Evidence loaded"}).waitFor();
 await page.screenshot({path:path.join(out,"master-chart.png"),fullPage:true});
 checks.push({check:"historical_master_chart",panels:await page.locator(".chart").count(),svg:await page.locator(".chart svg").count()});
 await page.locator(".chart svg").first().hover({position:{x:500,y:80}});
 if(!await page.locator("#tooltip").isVisible())throw Error("Chart tooltip missing");
 checks.push({check:"source_linked_cursor",tooltip:await page.locator("#tooltip").innerText()});
 await page.getByRole("button",{name:"Evidence & QC",exact:true}).click();
 await page.screenshot({path:path.join(out,"evidence-qc.png"),fullPage:true});
 await page.getByRole("button",{name:"Load first 200 evidence records"}).click();
 await page.locator("#observation-table tbody tr").first().waitFor();
 checks.push({check:"evidence_table",rows:await page.locator("#observation-table tbody tr").count()});
 await page.getByRole("button",{name:"Microscopy",exact:true}).click();
 await page.locator("#images img").first().waitFor();
 checks.push({check:"microscopy_previews",count:await page.locator("#images img").count()});
 const rid="SOFTWARE-CHECK-"+Date.now();
 await page.getByRole("button",{name:"Import evidence",exact:true}).click();
 await page.locator("#file").setInputFiles({name:"software-fixture.csv",mimeType:"text/csv",buffer:Buffer.from("timestamp,parameter_code,raw_value,raw_unit\n2026-08-30T22:00:00+05:00,ph,\"7,1\",1\n2026-08-30T23:00:00+05:00,ph,#DIV/0!,1\n")});
 await page.getByRole("button",{name:"Preview & inspect QC"}).click();
 await page.locator("#mapping").waitFor({state:"visible"});
 await page.locator("#new-run").fill(rid);
 await page.locator("#classification").selectOption("source-derived");
 await page.getByRole("button",{name:"Normalize & retain import"}).click();
 await page.locator("#message").filter({hasText:"2 records normalized"}).waitFor();
 const submitted=await context.request.post(base+"/api/v1/jobs",{data:{kind:"historical",run:rid}});
 if(submitted.status()!==202)throw Error("Import job rejected");
 const job=(await submitted.json()).id;
 let done;
 for(let i=0;i<90;i++){await page.waitForTimeout(1000);done=await (await context.request.get(base+"/api/v1/jobs/"+job)).json();if(!["queued","running"].includes(done.status))break;}
 if(done.status!=="completed")throw Error("Import job failed: "+JSON.stringify(done));
 const reviewed=await (await context.request.get(base+"/api/v1/runs/"+rid)).json();
 if(reviewed.series.length!==1||reviewed.model_results.status!=="blocked")throw Error("Imported chart/model gate mismatch");
 checks.push({check:"uploaded_run_job_and_chart",status:done.status,chart_points:reviewed.series.length,biological_model:"correctly gated"});
 await page.locator("#run").selectOption(rid);
 await page.getByRole("button",{name:"Models & validation",exact:true}).click();
 await page.locator("#message").filter({hasText:"Evidence loaded"}).waitFor();
 await page.locator("#review-reason").fill("Automated software fixture: deferred pending invented test input; no scientific judgment.");
 await page.getByRole("button",{name:"Save researcher review",exact:true}).click();
 await page.locator("#message").filter({hasText:"Researcher review saved"}).waitFor();
 const reviews=await (await context.request.get(base+"/api/v1/runs/"+rid+"/hypothesis-reviews")).json();
 if(reviews.reviews.length!==1||reviews.reviews[0].status!=="deferred")throw Error("Researcher review did not persist");
 checks.push({check:"researcher_review_persisted",status:"passed",synthetic_fixture:true});
 const response=await context.request.get(base+"/api/v1/runs/"+rid+"/observations");
 const rows=(await response.json()).rows;
 if(rows[0].value!==7.1||rows[1].value!==null||rows[1].accepted!==false)throw Error("Normalization/QC mismatch");
 for(const name of ["observations.csv","observations.parquet","result.json","manifest.json","chart.svg","chart.png","report.html","evaluation.csv"]){
  const r=await context.request.get(base+"/api/v1/runs/"+rid+"/exports/"+name);
  if(r.status()!==200||(await r.body()).length===0)throw Error("Export failed: "+name);
  checks.push({check:"private_export",name,status:r.status()});
 }
 checks.push({check:"browser_upload_mapping_qc_export",status:"passed",record_count:rows.length,synthetic_fixture:true});
 const schema=await context.request.get(base+"/api/v1/openapi.json");
 fs.writeFileSync(path.join(out,"openapi.json"),JSON.stringify(await schema.json(),null,2));
 if(errors.length)throw Error("Browser errors: "+errors.join("; "));
 await page.locator("#run").selectOption("LAB005-2026-08");
 await page.getByRole("button",{name:"Master chart",exact:true}).click();
 await page.locator("#message").filter({hasText:"Evidence loaded"}).waitFor();
 await page.screenshot({path:path.join(out,"master-viewport.png")});
 // Remove only this script's known test-run exports. Never recursive deletion.
 const testFolder=path.resolve(privateDir,"runs",rid),allowedRoot=path.resolve(privateDir,"runs")+path.sep;
 if(!testFolder.startsWith(allowedRoot)||!rid.startsWith("SOFTWARE-CHECK-"))throw Error("Unsafe test cleanup path");
 for(const name of ["observations.csv","observations.parquet","result.json","manifest.json","chart.svg","chart.png","report.html","evaluation.csv"])fs.unlinkSync(path.join(testFolder,name));
 fs.rmdirSync(testFolder);
 fs.unlinkSync(path.join(privateDir,"reviews",rid+".jsonl"));
 await browser.close();await client.dispose();
 const report={checked_at:new Date().toISOString(),base,checks,browser_errors:errors,status:"passed"};
 fs.writeFileSync(path.join(out,"browser-checks.json"),JSON.stringify(report,null,2));
 console.log(JSON.stringify({status:"passed",checks:checks.length,browser_errors:errors.length,screenshot:"m10/private/verification/master-viewport.png"}));
})().catch(async e=>{console.error(e.stack);if(activeBrowser)await activeBrowser.close();process.exitCode=1;});
